export const NATURAL_KOREAN_RULES = `
NATURAL KOREAN — highest priority (an awkward sentence is worse than an off-topic one):
1. Every Korean sentence you write must be something a native speaker would actually say or write. If it sounds translated from English, rewrite it.
2. Drop the subjects/pronouns Korean leaves implicit — do not start every sentence with 저는/나는/그는/그녀는. Never use 당신 for "you": omit it or use a name/title.
3. Natural collocations: 사진을 찍다 (not 만들다), 약을 먹다, 결정을 내리다, 샤워를 하다, 시험을 보다, 마음에 들다, 돈을 쓰다.
4. Native vs Sino-Korean numbers with counters: 사과 세 개, 두 시 삼십 분, 삼 층, 이십 분, 다섯 명.
5. Topic fit is secondary: a natural everyday sentence beats one that forces the topic word in.
6. One clear idea per example. Starter/Beginner: short, concrete, high-frequency words only.
7. Speech level fits the situation: default 해요체 for examples; 반말 only between close friends/family and never mixed with 존댓말 in one line; honorifics (-시-, 께서, 드리다) only toward elders/superiors, never for oneself.
8. No literal English idioms, invented words or fake Konglish (real loanwords like 핸드폰 are fine).
9. English translations convey the meaning naturally, not word-for-word.
Before answering, re-read every Korean sentence once and replace anything a Korean teacher would mark as awkward.
`
