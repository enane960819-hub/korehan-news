// Builds supabase/migrations/20261028_topik_b_seed.sql from items.mjs.
// node --experimental-strip-types scripts/topik/build.ts
import { writeFileSync } from 'node:fs'
import { TESTS, shape } from './shape.ts'
import { lint } from './lint.ts'

// Stage 1 of the review (REVIEW.md): no seed is written while any check fails.
const findings = lint()
const errors = findings.filter((f) => f.level === 'error')
for (const f of findings) console.log(`${f.level === 'error' ? 'ERROR' : 'warn '} ${f.id}: ${f.msg}`)
if (errors.length) { console.error(`\n${errors.length} lint error(s) — fix them before building.`); process.exit(1) }

const q = (s: unknown) => s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'"

const tests: string[] = [], items: string[] = []
const json: any = { tests: [], items: [] }   // TOPIK_JSON=path → test fixture
const seen = new Set<string>()
for (const t of TESTS as any[]) {
  json.tests.push({ id: t.id, level: t.level, section: t.section, kind: t.kind, title: t.title, minutes: t.minutes, free: t.free, sort: t.sort, number: t.number || null, status: 'published' })
  tests.push(`  (${q(t.id)}, ${q(t.level)}, ${q(t.section)}, ${q(t.kind)}, ${q(t.title)}, ${t.minutes}, ${t.free}, ${t.sort}, ${t.number || 'null'}, 'draft')`)
  const counts: Record<number, number> = {}
  for (const it of t.items) {
    const x = shape(t, it)
    const { id, choices, answer, passage, script, group } = x
    if (seen.has(id)) throw new Error('duplicate ' + id)
    seen.add(id)
    counts[answer] = (counts[answer] || 0) + 1
    const instruction = it.ins || null
    const media = it.m || null
    json.items.push({ id, test_id: t.id, n: it.n, type: it.t, group_key: group, passage, question: it.q || null, choices, answer, explanation: it.e || null, instruction, script, media })
    items.push(`  (${q(id)}, ${q(t.id)}, ${it.n}, ${q(it.t)}, ${q(group)}, ${q(passage)}, ${q(it.q || null)}, ${q(JSON.stringify(choices))}::jsonb, ${answer}, ${q(it.e || null)}, ${q(instruction)}, ${script ? q(JSON.stringify(script)) + '::jsonb' : 'null'}, ${media ? q(JSON.stringify(media)) + '::jsonb' : 'null'})`)
  }
  console.log(t.id, t.items.length, 'answers', JSON.stringify(counts))
}

const sql = `-- auto-apply
-- TOPIK-style practice — seed (generated by scripts/topik/build.ts; edit items.mjs, not this file).
-- New tests arrive as drafts; the admin publishes them after reviewing every
-- question in the app (REVIEW.md, stage 3). Status is never touched on update.
insert into public.topik_tests (id, level, section, kind, title, minutes, free, sort, number, status)
values
${tests.join(',\n')}
on conflict (id) do update set level = excluded.level, section = excluded.section, kind = excluded.kind,
  title = excluded.title, minutes = excluded.minutes, free = excluded.free, sort = excluded.sort,
  number = coalesce(excluded.number, public.topik_tests.number);

insert into public.topik_items (id, test_id, n, type, group_key, passage, question, choices, answer, explanation, instruction, script, media)
values
${items.join(',\n')}
on conflict (id) do update set n = excluded.n, type = excluded.type, group_key = excluded.group_key,
  passage = excluded.passage, question = excluded.question, choices = excluded.choices,
  answer = excluded.answer, explanation = excluded.explanation, instruction = excluded.instruction,
  script = excluded.script, media = excluded.media;
`
writeFileSync(new URL('../../supabase/migrations/20261028_topik_b_seed.sql', import.meta.url), sql)
if (process.env.TOPIK_JSON) writeFileSync(process.env.TOPIK_JSON, JSON.stringify(json))
