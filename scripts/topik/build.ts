// Builds supabase/migrations/20261028_topik_b_seed.sql from items.mjs.
// node --experimental-strip-types scripts/topik/build.ts
import { writeFileSync } from 'node:fs'
import { TESTS, PASSAGES } from './items.mjs'

const q = (s: unknown) => s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'"
// Deterministic shuffle per item so the right answer isn't always ①.
function seeded(str: string) { let h = 2166136261; for (const c of str) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619) } return () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 10000) / 10000 } }

const tests: string[] = [], items: string[] = []
const json: any = { tests: [], items: [] }   // TOPIK_JSON=path → test fixture
const seen = new Set<string>()
for (const t of TESTS as any[]) {
  json.tests.push({ id: t.id, level: t.level, section: t.section, kind: t.kind, title: t.title, minutes: t.minutes, free: t.free, sort: t.sort })
  tests.push(`  (${q(t.id)}, ${q(t.level)}, ${q(t.section)}, ${q(t.kind)}, ${q(t.title)}, ${t.minutes}, ${t.free}, ${t.sort})`)
  const counts: Record<number, number> = {}
  for (const it of t.items) {
    const id = `${t.id}-${it.n}`
    if (seen.has(id)) throw new Error('duplicate ' + id)
    seen.add(id)
    let choices: string[], answer: number
    if (it.fixed) { choices = it.choices; answer = it.ans }
    else {
      if (!it.a || !Array.isArray(it.w) || it.w.length !== 3) throw new Error('bad item ' + id)
      const all = [it.a, ...it.w]
      if (new Set(all).size !== 4) throw new Error('duplicate choice ' + id)
      const r = seeded(id)
      const order = [0, 1, 2, 3]
      for (let i = 3; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [order[i], order[j]] = [order[j], order[i]] }
      choices = order.map((i) => all[i]); answer = order.indexOf(0) + 1
    }
    counts[answer] = (counts[answer] || 0) + 1
    const passage = it.g ? PASSAGES[it.g] : (it.p || null)
    if (it.g && !passage) throw new Error('missing passage ' + it.g)
    json.items.push({ id, test_id: t.id, n: it.n, type: it.t, group_key: it.g || null, passage, question: it.q || null, choices, answer, explanation: it.e || null })
    items.push(`  (${q(id)}, ${q(t.id)}, ${it.n}, ${q(it.t)}, ${q(it.g || null)}, ${q(passage)}, ${q(it.q || null)}, ${q(JSON.stringify(choices))}::jsonb, ${answer}, ${q(it.e || null)})`)
  }
  console.log(t.id, t.items.length, 'answers', JSON.stringify(counts))
}

const sql = `-- auto-apply
-- TOPIK-style practice — seed (generated by scripts/topik/build.ts; edit items.mjs, not this file).
insert into public.topik_tests (id, level, section, kind, title, minutes, free, sort)
values
${tests.join(',\n')}
on conflict (id) do update set level = excluded.level, section = excluded.section, kind = excluded.kind,
  title = excluded.title, minutes = excluded.minutes, free = excluded.free, sort = excluded.sort;

insert into public.topik_items (id, test_id, n, type, group_key, passage, question, choices, answer, explanation)
values
${items.join(',\n')}
on conflict (id) do update set n = excluded.n, type = excluded.type, group_key = excluded.group_key,
  passage = excluded.passage, question = excluded.question, choices = excluded.choices,
  answer = excluded.answer, explanation = excluded.explanation;
`
writeFileSync(new URL('../../supabase/migrations/20261028_topik_b_seed.sql', import.meta.url), sql)
if (process.env.TOPIK_JSON) writeFileSync(process.env.TOPIK_JSON, JSON.stringify(json))
