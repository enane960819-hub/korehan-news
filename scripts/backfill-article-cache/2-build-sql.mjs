// Step 2: read data/responses/{id}.json + data/prompts/{id}.meta.json,
// build the post-processed cache row, emit data/backfill.sql.
// Each response file is the raw JSON {sentences:[...]} the AI produced.
//
// usage: node 2-build-sql.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCacheRow, sqlEscape } from './lib.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(__dirname, 'data');
const PROMPTS = path.join(DATA, 'prompts');
const RESPONSES = path.join(DATA, 'responses');
const OUT = path.join(DATA, 'backfill.sql');

const responses = fs.readdirSync(RESPONSES).filter((f) => f.endsWith('.json'));
if (!responses.length) {
  console.error(`no responses in ${RESPONSES}`);
  process.exit(1);
}

const stmts = ['-- article_cache backfill — generated by 2-build-sql.mjs', 'BEGIN;'];
let n = 0;
for (const file of responses) {
  const id = file.replace(/\.json$/, '');
  const metaPath = path.join(PROMPTS, id + '.meta.json');
  if (!fs.existsSync(metaPath)) { console.warn('missing meta:', id); continue; }
  const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
  const raw = fs.readFileSync(path.join(RESPONSES, file), 'utf8');
  let parsed;
  try {
    const clean = raw.replace(/^```json?/, '').replace(/^```/, '').replace(/```$/, '').trim();
    const oi = clean.indexOf('{'), ei = clean.lastIndexOf('}');
    parsed = JSON.parse(clean.slice(oi, ei + 1));
  } catch (e) {
    console.warn('skip — bad JSON:', id, e.message);
    continue;
  }
  const aiSentences = Array.isArray(parsed.sentences) ? parsed.sentences : [];
  if (!aiSentences.length) { console.warn('skip — empty sentences:', id); continue; }

  const row = buildCacheRow({
    articleId: meta.id,
    body: meta.body,
    level: meta.level,
    aiSentences,
  });

  // Schema-aware: try wide (one row per article_id with translation/vocab/grammar
  // columns) first. The KV-shaped table needs different writes — admin code
  // tries wide then KV-fallbacks on column-missing errors. Wide form is what
  // the production schema in this repo uses (per article_cache.upsert sites).
  const cols = ['article_id', 'translation', 'vocab', 'grammar'];
  const vals = [
    sqlEscape(row.article_id),
    sqlEscape(row.translation),
    row.vocab ? sqlEscape(row.vocab) : 'NULL',
    row.grammar ? sqlEscape(row.grammar) : 'NULL',
  ];
  stmts.push(
    `INSERT INTO article_cache (${cols.join(', ')}) VALUES (${vals.join(', ')}) ` +
    `ON CONFLICT (article_id) DO UPDATE SET ` +
    `translation = EXCLUDED.translation, ` +
    `vocab = COALESCE(EXCLUDED.vocab, article_cache.vocab), ` +
    `grammar = COALESCE(EXCLUDED.grammar, article_cache.grammar);`
  );
  n++;
}
stmts.push('COMMIT;');
fs.writeFileSync(OUT, stmts.join('\n') + '\n');
console.log(`wrote ${n} INSERTs to ${OUT}`);
