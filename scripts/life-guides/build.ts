// Builds supabase/migrations/20261028_life_guides_b_seed.sql from guides.mjs.
// node --experimental-strip-types scripts/life-guides/build.ts
import { writeFileSync } from 'node:fs'
import { romanize } from '../../supabase/functions/_shared/romanize.ts'
import { GUIDES, CHECKED } from './guides.mjs'

const q = (s: string) => "'" + String(s).replace(/'/g, "''") + "'"
const j = (v: unknown) => q(JSON.stringify(v)) + '::jsonb'

const rows = GUIDES.map((g: any) => {
  const seen = new Set<string>()
  const terms: any[] = []
  for (const st of g.steps) for (const m of st.matchAll(/\{\{([^|}]+)\|([^}]+)\}\}/g)) {
    const ko = m[1].trim(), en = m[2].trim()
    if (seen.has(ko)) continue
    seen.add(ko)
    terms.push({ ko, rom: romanize(ko), en })
  }
  return `  (${q(g.slug)}, ${q(g.category)}, ${g.featured}, ${g.sort}, ${q(g.title)}, ${q(g.summary)}, ${j(g.steps)}, ${j(terms)}, ${j(g.phrases)}, ${j(g.sources)}, ${q(CHECKED)}::date, 'published')`
})

const sql = `-- auto-apply
-- Life in Korea guides — seed (generated by scripts/life-guides/build.ts; edit guides.mjs, not this file).
-- Re-running updates text in place; unchanged rows keep their qa_at (the
-- requeue trigger only fires on real changes).
insert into public.life_guides (slug, category, featured, sort, title, summary, steps, terms, phrases, sources, checked_at, status)
values
${rows.join(',\n')}
on conflict (slug) do update set
  category = excluded.category, featured = excluded.featured, sort = excluded.sort,
  title = excluded.title, summary = excluded.summary, steps = excluded.steps,
  terms = excluded.terms, phrases = excluded.phrases, sources = excluded.sources,
  checked_at = excluded.checked_at;
`
writeFileSync(new URL('../../supabase/migrations/20261028_life_guides_b_seed.sql', import.meta.url), sql)
console.log('guides:', GUIDES.length)
