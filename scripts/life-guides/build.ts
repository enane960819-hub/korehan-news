// Builds the Life in Korea seed + the static copy the page paints from.
//   guides.mjs       — the first 14 guides
//   guides-more.mjs  — v2 fields for them (EXTRA), new guides (MORE), OFFICES
// Output: supabase/migrations/20261029_life_guides_d_seed.sql,
//         korehan/data/life-guides.json, korehan/data/immigration-offices.json
// node --experimental-strip-types scripts/life-guides/build.ts
import { writeFileSync } from 'node:fs'
import { romanize } from '../../supabase/functions/_shared/romanize.ts'
import { GUIDES, CHECKED } from './guides.mjs'
import { EXTRA, MORE, OFFICES, CHECKED2 } from './guides-more.mjs'
import { TRANSPORT } from './guides-transport.mjs'
import { MORE2 } from './guides-more2.mjs'

const q = (s: string) => "'" + String(s).replace(/'/g, "''") + "'"
const j = (v: unknown) => q(JSON.stringify(v)) + '::jsonb'
const V2 = ['facts', 'checklist', 'tips', 'tipsNote', 'warn', 'items', 'itemsTitle', 'places', 'offices']

const all = [
  ...GUIDES.map((g: any) => ({ ...g, ...(EXTRA[g.slug] || {}), checked: EXTRA[g.slug] ? CHECKED2 : CHECKED })),
  ...MORE.map((g: any) => ({ ...g, checked: CHECKED2 })),
  ...TRANSPORT.map((g: any) => ({ ...g, checked: CHECKED2 })),
  ...MORE2.map((g: any) => ({ ...g, checked: CHECKED2 })),
]
const slugs = new Set<string>()
const fixture: any[] = []
const rows = all.map((g: any) => {
  if (slugs.has(g.slug)) throw new Error('duplicate slug ' + g.slug)
  slugs.add(g.slug)
  for (const k of ['slug', 'category', 'title', 'summary', 'steps', 'phrases', 'sources']) if (!g[k]) throw new Error(g.slug + ' missing ' + k)
  const seen = new Set<string>()
  const terms: any[] = []
  for (const st of g.steps) for (const m of st.matchAll(/\{\{([^|}]+)\|([^}]+)\}\}/g)) {
    const ko = m[1].trim(), en = m[2].trim()
    if (seen.has(ko)) continue
    seen.add(ko)
    terms.push({ ko, rom: /[가-힣]/.test(ko) ? romanize(ko) : '', en })
  }
  const extra: Record<string, unknown> = {}
  for (const k of V2) if (g[k] != null) extra[k] = g[k]
  fixture.push({ slug: g.slug, category: g.category, featured: !!g.featured, sort: g.sort, title: g.title, summary: g.summary, steps: g.steps, terms, phrases: g.phrases, sources: g.sources, checked_at: g.checked, extra })
  return `  (${q(g.slug)}, ${q(g.category)}, ${!!g.featured}, ${g.sort}, ${q(g.title)}, ${q(g.summary)}, ${j(g.steps)}, ${j(terms)}, ${j(g.phrases)}, ${j(g.sources)}, ${j(extra)}, ${q(g.checked)}::date, 'published')`
})

const sql = `-- auto-apply
-- Life in Korea guides v2 — seed, ${all.length} guides, re-applied after the Nano → Micro resize (generated by scripts/life-guides/build.ts; edit the .mjs files, not this file).
-- Upsert keeps admin-added photos (separate column) and qa_at on unchanged rows.
insert into public.life_guides (slug, category, featured, sort, title, summary, steps, terms, phrases, sources, extra, checked_at, status)
values
${rows.join(',\n')}
on conflict (slug) do update set
  category = excluded.category, featured = excluded.featured, sort = excluded.sort,
  title = excluded.title, summary = excluded.summary, steps = excluded.steps,
  terms = excluded.terms, phrases = excluded.phrases, sources = excluded.sources,
  extra = excluded.extra, checked_at = excluded.checked_at;
`
writeFileSync(new URL('../../supabase/migrations/20261029_life_guides_d_seed.sql', import.meta.url), sql)
writeFileSync(new URL('../../korehan/data/life-guides.json', import.meta.url), JSON.stringify(fixture))
writeFileSync(new URL('../../korehan/data/immigration-offices.json', import.meta.url), JSON.stringify(OFFICES))
console.log('guides:', all.length, 'categories:', JSON.stringify(all.reduce((m: any, g: any) => (m[g.category] = (m[g.category] || 0) + 1, m), {})))
